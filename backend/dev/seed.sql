INSERT INTO RUNTPROD.RA_AUTOMOTOR (
  AUTOMOTOR_NROREGVEH, AUTOMOTOR_PLACA_NUMPLACA, AUTOMOTOR_TIPOSERVI_IDETIPSER,
  AUTOMOTOR_CLASVEHIC_IDCLASE, AUTOMOTOR_COLOR_IDCOLOR, AUTOMOTOR_MARCA_IDMARCA,
  AUTOMOTOR_ANOFABRIC, AUTOMOTOR_MODELO, AUTOMOTOR_FECHREGIS, AUTOMOTOR_CILINDRAJ,
  AUTOMOTOR_ESTAVEHIC_NOMBRE, AUTOMOTOR_FECHCANCE, AUTOMOTOR_NROCHASIS,
  AUTOMOTOR_NROMOTOR, AUTOMOTOR_NROSERIE, AUTOMOTOR_IDVEUNINT, AUTOMOTOR_FECHACTUA,
  AUTOMOTOR_AUTOTRANS_IDAUTTRA
)
SELECT
  level,
  CHR(65 + MOD(TRUNC(level / 676000), 26)) || CHR(65 + MOD(TRUNC(level / 26000), 26)) ||
    CHR(65 + MOD(TRUNC(level / 1000), 26)) || LPAD(MOD(level, 1000), 3, '0'),
  1 + MOD(level, 5),
  1 + MOD(level, 4),
  1 + MOD(level * 3, 11),
  100 + MOD(level, 40),
  2005 + MOD(level, 21),
  2006 + MOD(level, 21),
  TRUNC(SYSDATE) - MOD(level * 17, 4000),
  CASE WHEN MOD(level, 4) = 2 THEN 125 + MOD(level, 100) ELSE 1000 + MOD(level * 11, 2600) END,
  CASE MOD(level, 20) WHEN 0 THEN 'CANCELADO' WHEN 7 THEN 'INMOVILIZADO' ELSE 'ACTIVO' END,
  CASE WHEN MOD(level, 20) = 0 THEN TRUNC(SYSDATE) - MOD(level, 900) ELSE NULL END,
  'CH' || LPAD(level, 12, '0'),
  'MT' || LPAD(level, 12, '0'),
  'SR' || LPAD(level, 12, '0'),
  'VIN' || LPAD(level, 14, '0'),
  TRUNC(SYSDATE) - MOD(level, 60),
  -- Multiplied by 7 so the municipality is not correlated with the state,
  -- which also cycles on MOD(level, 20).
  CASE
    WHEN MOD(level * 7, 20) BETWEEN 0 AND 5  THEN 11001
    WHEN MOD(level * 7, 20) BETWEEN 6 AND 8  THEN 5001
    WHEN MOD(level * 7, 20) BETWEEN 9 AND 10 THEN 76001
    WHEN MOD(level * 7, 20) BETWEEN 11 AND 12 THEN 8001
    WHEN MOD(level * 7, 20) = 13 THEN 13001
    WHEN MOD(level * 7, 20) = 14 THEN 68001
    WHEN MOD(level * 7, 20) = 15 THEN 54001
    WHEN MOD(level * 7, 20) = 16 THEN 66001
    WHEN MOD(level * 7, 20) = 17 THEN 17001
    WHEN MOD(level * 7, 20) = 18 THEN 5400
    ELSE 52399
  END
FROM dual CONNECT BY level <= 60000;

