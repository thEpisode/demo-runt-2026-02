SELECT m.MUNICPIO_NOMBRE, COUNT(*) AS vehiculos
  FROM RUNTPROD.RA_AUTOMOTOR a
  JOIN RUNTPROD.PA_MUNICPIO m ON a.AUTOMOTOR_AUTOTRANS_IDAUTTRA = m.MUNICPIO_DIVIPOL
 GROUP BY m.MUNICPIO_NOMBRE
 ORDER BY vehiculos DESC;

